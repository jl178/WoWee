/// The kind of a GameError by its key, or Error for a key the table lacks
/// (the commonest kind, and the one a caller raising an error expects).
inline GameMessageKind gameMessageKind(std::string_view key) {
    for (const auto& row : kGameErrorTable)
        if (key == row.key) return row.kind;
    return GameMessageKind::Error;
}

